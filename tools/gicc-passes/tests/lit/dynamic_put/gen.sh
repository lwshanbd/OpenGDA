#!/usr/bin/env bash
# Regenerate the run-time counting lit tests from Inputs/dynamic.cpp: its
# host IR (dynamic_host.ll) and its NVPTX device IR before any optimization
# (dynamic_device.ll). Run-time counting is wired on InfiniBand only, so the
# IR is NVPTX, from the LLVM the Maple plugin is built against.
#
# Usage: LLVM=<llvm prefix with NVPTX offload> CUDA=<cuda> MPI_INC=<mpi include> ./gen.sh
set -euo pipefail
cd "$(dirname "$0")"
LLVM=${LLVM:-/shared/data1/Users/l1065028/llvm-22.1.7}
CUDA=${CUDA:-/hrtc/apps/cuda/12.4.131/aarch64/rocky9}
MPI_INC=${MPI_INC:-/hrtc/apps/mpi/openmpi/aarch64/rocky9/5.0.5/gcc/11.4.1/cuda.12.4/include}
ROOT=$(cd ../../../../.. && pwd)
FLAGS=(-fopenmp --offload-arch=sm_90 --cuda-path="$CUDA" -Wno-unknown-cuda-version -include string
       -std=gnu++17 -DGICC_BOOTSTRAP_MPI=1 -DGICC_PLATFORM_MLX5 -DGICC_GPU_CUDA=1
       -I"$ROOT" -I"$ROOT/src" -I"$CUDA/include" -isystem "$MPI_INC")

src_ir() {   # extra clang flags
    "$LLVM/bin/clang++" "${FLAGS[@]}" "$@" -S -emit-llvm Inputs/dynamic.cpp -o - 2>/dev/null |
        grep -v '^; ModuleID'
}

{
    cat <<'HEAD'
; Generated by gen.sh from Inputs/dynamic.cpp (host side) -- do not edit.
;
; An ompx_put_signal after a launch is found like an ompx_put, recorded as
; a signal, and bracketed by the signal forms of the post and the done.
; RUN: rm -rf %t.meta && mkdir -p %t.meta
; RUN: env GICC_MODE=put-discover GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -disable-output %s 2>&1 | %FileCheck %s --check-prefix=FIND
; RUN: cat %t.meta/after-*.json | %FileCheck %s --check-prefix=JSON
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -S %s 2>/dev/null | %FileCheck %s --check-prefix=BRACKET
;
; FIND-DAG: [gicc-after] __omp_offloading_{{.*}}scatter{{.*}}: 1 put(s) after the launch can go from the kernel
; FIND-DAG: [gicc-after] __omp_offloading_{{.*}}tally{{.*}}: 1 put(s) after the launch can go from the kernel
; JSON-DAG: {"kernel":"__omp_offloading_{{[^"]*}}scatter{{[^"]*}}","signals":[true],"src_args":[{{[0-9]+}}]}
; JSON-DAG: {"kernel":"__omp_offloading_{{[^"]*}}tally{{[^"]*}}","src_args":[{{[0-9]+}}]}
;
; BRACKET-LABEL: define {{.*}}@_Z7scatter
; BRACKET: call void @ompx__after_post_signal(i64 [[H:-?[0-9]+]], i32 0, i32 {{[0-9]+}}, i32 1, i32 %5, ptr %6, ptr %0, i64 {{%.*}}, i64 {{%.*}}, i32 3, i64 %7)
; BRACKET: call i32 @__tgt_target_kernel(
; BRACKET: call void @ompx__after_done_signal(i64 [[H]], i32 0, i32 %5, ptr %6, ptr %0, i64 {{%.*}}, i32 3, i64 %7)
; BRACKET-NOT: call void @ompx_put_signal_host(
; BRACKET-LABEL: define {{.*}}@_Z5tally
; BRACKET: call void @ompx__after_post(
; BRACKET: call void @ompx__after_done(
;
HEAD
    sed 's/^/; /; s/ *$//' Inputs/dynamic.cpp
    echo
    src_ir --offload-host-only -O2
} > dynamic_host.ll

{
    cat <<'HEAD'
; Generated by gen.sh from Inputs/dynamic.cpp (device side) -- do not edit.
;
; The sites come from the host test's first pass. With GICC_DYNAMIC=1 the
; scatter kernel, which the chunk analysis cannot split, counts its stores
; at run time; the tally kernel's atomic keeps its put on the host. Without
; it neither kernel changes.
; RUN: rm -rf %t.meta && mkdir -p %t.meta
; RUN: env GICC_MODE=put-discover GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -disable-output %S/dynamic_host.ll 2>/dev/null
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta GICC_DYNAMIC=1 %opt \
; RUN:   -load-pass-plugin=%gicc_passes_so -passes='default<O3>' -S %s 2>&1 | %FileCheck %s
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes='default<O3>' -S %s 2>&1 | %FileCheck %s --check-prefix=OFF
;
; CHECK: [gicc-chunk] kernel __omp_offloading_{{.*}}scatter
; CHECK: put 0: an ompx_put_signal, sent from the kernel only by run-time counting
; CHECK-DAG: [gicc-dyn] __omp_offloading_{{.*}}scatter{{.*}}: put 0 (ompx_put_signal) goes from the kernel by run-time counting, {{[1-9][0-9]*}} store(s) counted
; CHECK-DAG: [gicc-dyn] __omp_offloading_{{.*}}tally{{.*}}: the put after it stays on the host: an atomic in
; The kernel reads the post into team memory as its user code starts; the
; stores count into it, and the flush is inlined (no call is left).
; CHECK-LABEL: define {{.*}} @__omp_offloading_{{.*}}scatter
; CHECK: call void @ompx__dyn_begin(i64 {{-?[0-9]+}}, i32 0, i32 {{[0-9]+}}, ptr {{%.*}}, ptr addrspacecast (ptr addrspace(3) @gicc.dyn.post to ptr))
; CHECK-NOT: call void @ompx__dyn_flush
; CHECK: atomicrmw add
; CHECK-LABEL: define {{.*}} @__omp_offloading_{{.*}}tally
; CHECK-NOT: ompx__dyn_begin
; CHECK: ret void
;
; OFF-NOT: [gicc-dyn]
; OFF-NOT: call void @ompx__dyn_begin(
;
HEAD
    sed 's/^/; /; s/ *$//' Inputs/dynamic.cpp
    echo
    src_ir --offload-device-only -O3 -Xclang -disable-llvm-passes
} > dynamic_device.ll
