#!/usr/bin/env bash
# Regenerate the box-form pipelined-put lit tests from Inputs/*.cpp.
#
# Each Inputs/<case>.cpp is compiled to AMDGPU OpenMP device IR and carries
# its own CHECK lines; <case>.ll is the RUN lines, the source as comments
# and the IR. The IR comes from LLVM 19 (ROCm 6.4 on Tioga), which LLVM 21
# also reads, so the tests run against a plugin built for either.
#
# Usage: LLVM=<llvm prefix with AMDGPU offload> ./gen.sh
set -euo pipefail
cd "$(dirname "$0")"
LLVM=${LLVM:-/opt/rocm-6.4.0/lib/llvm}

RUN='; RUN: env GICC_MODE=chunk-analyze %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-chunk-analysis -disable-output %s 2>&1 | %FileCheck %s'

device_ir() {   # source, extra clang flags
    "$LLVM/bin/clang++" -fopenmp --offload-arch=gfx90a --offload-device-only \
        -S -emit-llvm $2 "$1" -o - | grep -v '^; ModuleID'
}

for src in Inputs/*.cpp; do
    name=$(basename "$src" .cpp)
    {
        echo "; Generated by gen.sh from Inputs/$name.cpp -- do not edit."
        echo ";"
        echo "$RUN"
        echo ";"
        sed 's/^/; /; s/ *$//' "$src"
        echo
        device_ir "$src" -O2
    } > "$name.ll"
done

# A put in a combined construct's loop body is read only after the prep
# pass has run, so these go through the whole -O3 pipeline from IR before
# any optimization.
RUN_O3='; RUN: env GICC_MODE=chunk-analyze %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes='"'"'default<O3>'"'"' -disable-output %s 2>&1 | %FileCheck %s'
for src in InputsO3/*.cpp; do
    name=$(basename "$src" .cpp)
    {
        echo "; Generated by gen.sh from InputsO3/$name.cpp -- do not edit."
        echo ";"
        echo "$RUN_O3"
        echo ";"
        sed 's/^/; /; s/ *$//' "$src"
        echo
        device_ir "$src" "-O3 -Xclang -disable-llvm-passes"
    } > "$name.ll"
done

# The in-loop face put lowered: the marker is gone and the kernel is still
# SPMD (execution mode 2 in its environment).
{
    echo "; Generated by gen.sh: InputsO3/legal_inloop_face3d.cpp before any optimization,"
    echo "; lowered through default<O3> -- do not edit."
    echo ";"
    echo "; RUN: env GICC_MODE=chunk-lower %opt -load-pass-plugin=%gicc_passes_so \\"
    echo "; RUN:   -passes='default<O3>' -S %s 2>&1 | %FileCheck %s"
    echo ";"
    cat <<'CHECKS'
; CHECK: lowered: element grain over the box
; CHECK: _kernel_environment = {{.*}} { %struct.ConfigurationEnvironmentTy { i8 0, i8 {{[01]}}, i8 2,
; CHECK-LABEL: define {{.*}} @__omp_offloading_
; The kernel is SPMD, so it can send to a peer that is not IPC-mapped
; itself, by counting the teams past the range. The source states the put
; (after index -1).
; CHECK: call ptr @ompx__box_peer({{.*}}, i32 1, i32 -1, ptr addrspacecast (ptr addrspace(3) @gicc.box.counted to ptr))
; The team shares the residual copy.
; CHECK: call void @ompx__box_residual({{.*}}, i32 1)
; A counted put goes out in pieces, each counted on its own: 64 entries
; for the one put, filled by a loop, the first the whole range when it is
; one piece.
; CHECK: call i64 @ompx__box_piece(i64 {{.*}}, i32 64, i32 -1)
; CHECK: %iv = phi i64 [ 0,
; CHECK: getelementptr inbounds [64 x i64], ptr addrspace(3) @gicc.box.lo, i64 0, i64
; CHECK: call void @ompx__box_hull(
; CHECK: call void @ompx__box_plan(i32 64,
; CHECK: call void @__kmpc_distribute_static_init
; Before each chunk: the next chunk from the counter the teams share, its
; rotated bounds, then, once a counted put may be due, the count of a team
; past its range.
; CHECK: call i64 @ompx__box_grab(
; CHECK: [[UB:%.*]] = call i64 @llvm.umin.i64(
; CHECK: call i64 @ompx__box_due(i32 64, i64 %gicc.box.pos,
; CHECK: call void @__kmpc_parallel_51(
; And once past the loop, then the counter reset by the last team.
; CHECK: call i64 @ompx__box_due(i32 64, i64 9223372036854775806,
; CHECK: call void @ompx__box_grab_done(
; CHECK: call void @__kmpc_distribute_static_fini(
; CHECK-LABEL: define internal void @__omp_offloading_{{.*}}_omp_outlined_omp_outlined(
; CHECK: %gicc.box.in = and i1
; CHECK-NOT: ompx_pipelined_put
CHECKS
    echo
    device_ir InputsO3/legal_inloop_face3d.cpp "-O3 -Xclang -disable-llvm-passes"
} > lower_inloop_face3d.ll

# The whole -O3 pipeline from unoptimized IR: the prep pass keeps the
# region outlined, the put is lowered to the box element grain, and the
# put_no_db mirror leaves the repeated store alone.
{
    echo "; Generated by gen.sh: Inputs/legal_face3d.cpp before any optimization,"
    echo "; lowered through default<O3> -- do not edit."
    echo ";"
    echo "; RUN: env GICC_MODE=chunk-lower %opt -load-pass-plugin=%gicc_passes_so \\"
    echo "; RUN:   -passes='default<O3>' -S %s 2>&1 | %FileCheck %s"
    echo ";"
    cat <<'CHECKS'
; CHECK: lowered: element grain over the box
; The kernel resolves the peer, sends the unwritten part of the range, and
; hands the range and the peer offset to the region.
; CHECK-LABEL: define {{.*}} @__omp_offloading_
; A generic kernel cannot count the teams past the range: a peer that is
; not IPC-mapped is left to the next quiet.
; CHECK: [[PD:%.*]] = call ptr @ompx__box_peer(i32 {{%.*}}, ptr {{%.*}}, ptr {{%.*}}, i64 {{%.*}}, i32 0, i32 -1, ptr addrspacecast (ptr addrspace(3) @gicc.box.counted to ptr))
; The kernel is still generic when the pass runs, so one thread per team
; sends the residual.
; CHECK: call void @ompx__box_residual(ptr [[PD]], ptr {{%.*}}, i64 {{%.*}}, ptr {{%.*}}, i32 3, ptr addrspacecast (ptr addrspace(3) @gicc.box.stride to ptr), ptr addrspacecast (ptr addrspace(3) @gicc.box.extent to ptr), i64 4, i32 {{%.*}}, i32 0)
; CHECK: store i64 {{%.*}}, ptr addrspace(3) @gicc.box.delta
; CHECK: store i64 {{%.*}}, ptr addrspace(3) @gicc.box.start
; CHECK: store i64 {{%.*}}, ptr addrspace(3) @gicc.box.len
; CHECK: call void @__kmpc_distribute_static_init
; CHECK-NOT: ompx_pipelined_put
; A store in the range is repeated at the peer offset.
; CHECK-LABEL: define internal void @__omp_offloading_{{.*}}_omp_outlined_omp_outlined(
; CHECK: [[DELTA:%.*]] = load i64, ptr addrspace(3) @gicc.box.delta
; The put_no_db mirror checks the original store first; then the box check.
; CHECK: store float [[V:%[0-9]+]], ptr [[P:%[0-9]+]], align 4, !tbaa
; CHECK: %gicc.box.in = and i1
; CHECK-NEXT: br i1 %gicc.box.in
; CHECK: [[R:%.*]] = getelementptr i8, ptr [[P]], i64 [[DELTA]]
; CHECK-NEXT: store float [[V]], ptr [[R]], align 4, !gicc.repeat
; CHECK-NOT: gicc-chunk-noinline
; CHECK-NOT: ompx__box_due(
CHECKS
    echo
    device_ir Inputs/legal_face3d.cpp "-O3 -Xclang -disable-llvm-passes"
} > lower_face3d.ll
