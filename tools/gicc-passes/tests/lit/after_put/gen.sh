#!/usr/bin/env bash
# Regenerate the puts-after-a-launch lit tests from Inputs/after.cpp: its
# host IR (after_host.ll) and its device IR before any optimization
# (after_device.ll). The device test reads the sites the host test's first
# pass finds, so the kernel names agree. The same for the in-loop puts the
# host posts, from Inputs/loop.cpp (loop_device.ll, loop_host.ll); there
# the host test reads what the device test records.
#
# Usage: LLVM=<llvm prefix with AMDGPU offload> ./gen.sh
set -euo pipefail
cd "$(dirname "$0")"
LLVM=${LLVM:-/opt/rocm-6.4.0/lib/llvm}
ROOT=$(cd ../../../../.. && pwd)
MPI_INC=${MPI_INC:-/opt/cray/pe/mpich/9.0.1/ofi/cray/20.0/include}
FLAGS=(-fopenmp --offload-arch=gfx90a -std=gnu++17 -DGICC_BOOTSTRAP_MPI=1
       -DGICC_PLATFORM_OFI -DGICC_GPU_HIP=1 -DGICC_CPU_PROXY=1 -D__HIP_PLATFORM_AMD__=1
       -I"$ROOT" -I"$ROOT/src" -I"$LLVM/../../include" -isystem "$MPI_INC" -Wno-openmp-target)

ir() {   # extra clang flags
    src_ir Inputs/after.cpp "$@"
}
src_ir() {   # source, extra clang flags
    local src=$1
    shift
    "$LLVM/bin/clang++" "${FLAGS[@]}" "$@" -S -emit-llvm "$src" -o - 2>/dev/null |
        grep -v '^; ModuleID' | sed 's/captures(none)/nocapture/g'
}

{
    cat <<'HEAD'
; Generated by gen.sh from Inputs/after.cpp (host side) -- do not edit.
;
; First pass: the puts after each launch are found and recorded.
; RUN: rm -rf %t.meta && mkdir -p %t.meta
; RUN: env GICC_MODE=put-discover GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -disable-output %s 2>&1 | %FileCheck %s --check-prefix=FIND
; RUN: cat %t.meta/after-*.json | %FileCheck %s --check-prefix=JSON
; Second pass: each put is posted before the launch and made after it only
; if the kernel did not.
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -S %s 2>/dev/null | %FileCheck %s --check-prefix=BRACKET
;
; FIND-DAG: [gicc-after] __omp_offloading_{{.*}}fenced{{.*}}: a put stays after the kernel: code between the launch and the put may synchronize or write the source: ompx_barrier
; FIND-DAG: [gicc-after] __omp_offloading_{{.*}}step{{.*}}: 2 put(s) after the launch can go from the kernel
; FIND-DAG: [gicc-after] __omp_offloading_{{.*}}gated{{.*}}: 1 put(s) after the launch can go from the kernel
; JSON: "sites":[{"kernel":"__omp_offloading_{{[^"]*}}step{{[^"]*}}","src_args":[[[ARG:[0-9]+]],[[ARG]]]},{"kernel":"__omp_offloading_{{[^"]*}}gated{{[^"]*}}","src_args":[{{[0-9]+}}]}]
;
; BRACKET-LABEL: define {{.*}}@_Z4step
; BRACKET: call void @ompx__after_post(i64 [[H:-?[0-9]+]], i32 0, i32 {{[0-9]+}}, i32 {{%.*}}, i32 [[L:%[0-9]+]], ptr {{%[^,]+}}, ptr {{%[^,]+}}, i64 {{%[^,]+}}, i64
; BRACKET: call void @ompx__after_post(i64 [[H]], i32 1, i32 {{[0-9]+}}, i32 {{%.*}}, i32 [[R:%[0-9]+]], ptr {{%[^,]+}}, ptr {{%[^,]+}}, i64 {{%[^,]+}}, i64
; BRACKET: call i32 @__tgt_target_kernel(
; BRACKET: call void @ompx__after_done(i64 [[H]], i32 0, i32 [[L]],
; BRACKET: call void @ompx__after_done(i64 [[H]], i32 1, i32 [[R]],
; BRACKET-NOT: call void @ompx_put_host(
; BRACKET-LABEL: define {{.*}}@_Z6fenced
; BRACKET-NOT: ompx__after_post
; BRACKET: call void @ompx_barrier()
; BRACKET: call void @ompx_put_host(
; The gated region's put is posted before the launch; the run on the host
; posts nothing, and the done after both makes the put from the host.
; BRACKET-LABEL: define {{.*}}@_Z5gated
; BRACKET: call void @ompx__after_post(i64 [[G:-?[0-9]+]], i32 0,
; BRACKET: call i32 @__tgt_target_kernel(
; BRACKET: call void (ptr, i32, ptr, ...) @__kmpc_fork_teams(
; BRACKET: call void @ompx__after_done(i64 [[G]], i32 0,
; BRACKET-NOT: call void @ompx_put_host(
;
HEAD
    sed 's/^/; /; s/ *$//' Inputs/after.cpp
    echo
    ir --offload-host-only -O2
} > after_host.ll

DEV=$(ir --offload-device-only -O3 -Xclang -disable-llvm-passes)
FENCED=$(sed -n 's/^define .*@\(__omp_offloading_[A-Za-z0-9_]*fenced[A-Za-z0-9_]*\)(.*/\1/p' <<< "$DEV" | sed -n 1p)
# v's place among what the kernel is handed: its first pointer after the
# kernel's own first formal.
FENCED_ARG=$(grep -m1 "^define .*@$FENCED(" <<< "$DEV" |
    sed 's/^[^(]*(//; s/).*//' | tr ',' '\n' | tail -n +2 | grep -n 'ptr' | sed -n 1p | cut -d: -f1)
FENCED_ARG=$((FENCED_ARG - 1))
{
    cat <<HEAD
; Generated by gen.sh from Inputs/after.cpp (device side) -- do not edit.
;
; The sites come from the host test's first pass; one more names the
; fenced kernel, whose put the host would never post, to check that a put
; the kernel cannot send is left to the host without an error.
; RUN: rm -rf %t.meta && mkdir -p %t.meta
; RUN: env GICC_MODE=put-discover GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \\
; RUN:   -passes=gicc-after-put -disable-output %S/after_host.ll 2>/dev/null
; RUN: echo '{"sites":[{"kernel":"$FENCED","src_args":[$FENCED_ARG]}]}' > %t.meta/after-fenced.json
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \\
; RUN:   -passes='default<O3>' -S %s 2>&1 | %FileCheck %s
;
HEAD
    cat <<'CHECKS'
; The step kernel's two puts are proven and lowered; the fenced kernel's,
; which it could not send (it does not store every word), stays on the host
; without an error.
; CHECK: [gicc-chunk] kernel __omp_offloading_{{.*}}step
; CHECK: ompx_put after the kernel: LEGAL
; CHECK: ompx_put after the kernel: LEGAL
; CHECK: lowered: element grain over the box
; CHECK: [gicc-chunk] kernel __omp_offloading_{{.*}}fenced
; CHECK: ompx_put after the kernel: ILLEGAL: no store to {{.*}} runs on every iteration
; CHECK: [gicc-chunk] kernel __omp_offloading_{{.*}}gated
; CHECK: ompx_put after the kernel: LEGAL
; CHECK: lowered: element grain over the box
; CHECK-NOT: error
; The step kernel reads both posts before its loop and sends them itself,
; each by its index among the posts (the doorbell of one the host queued).
; CHECK-LABEL: define {{.*}} @__omp_offloading_{{.*}}step
; CHECK: call void @ompx__after_put(i64 {{-?[0-9]+}}, i32 0, i32 [[ARG:[0-9]+]],
; CHECK: call void @ompx__after_put(i64 {{-?[0-9]+}}, i32 1, i32 [[ARG]],
; CHECK-DAG: call ptr @ompx__box_peer({{.*}}, i32 {{[01]}}, i32 0, ptr
; CHECK-DAG: call ptr @ompx__box_peer({{.*}}, i32 {{[01]}}, i32 1, ptr
; CHECK-NOT: call void @ompx_pipelined_put
; Nothing of the fenced kernel's put is left.
; CHECK-LABEL: define {{.*}} @__omp_offloading_{{.*}}fenced
; CHECK-NOT: ompx__after_put(
; CHECK-NOT: call void @ompx_pipelined_put
; CHECK: ret void
; The gated kernel sends its put itself.
; CHECK-LABEL: define {{.*}} @__omp_offloading_{{.*}}gated
; CHECK: call void @ompx__after_put(i64 {{-?[0-9]+}}, i32 0,
CHECKS
    echo
    sed 's/^/; /; s/ *$//' Inputs/after.cpp
    echo
    printf '%s\n' "$DEV"
} > after_device.ll

{
    cat <<'HEAD'
; Generated by gen.sh from Inputs/loop.cpp (device side) -- do not edit.
;
; Each in-loop put the kernel lowers is recorded for the host compile, its
; arguments as expressions of the kernel's formals, and the kernel checks
; the host's post before it uses it.
; RUN: rm -rf %t.meta && mkdir -p %t.meta
; RUN: echo stale > %t.meta/loop-0000000000000000.json
; RUN: env GICC_MODE=put-discover GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -disable-output %S/loop_host.ll 2>/dev/null
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes='default<O3>' -S %s 2>&1 | %FileCheck %s
; RUN: cat %t.meta/loop-*.json | %FileCheck %s --check-prefix=JSON
;
; CHECK: [gicc-chunk] kernel __omp_offloading_{{.*}}face
; CHECK: ompx_pipelined_put: LEGAL
; CHECK: in-loop put posted by the host before each launch, as put 0
; CHECK: lowered: element grain over the box
; The face kernel reads the post before its loop; what that returns is the
; index the counting and the pieces use.
; CHECK-LABEL: define {{.*}} @__omp_offloading_{{.*}}face
; CHECK: [[A:%.*]] = call i32 @ompx__loop_after(i64 {{-?[0-9]+}}, i32 0, i32 [[ARG:[0-9]+]], i32 {{%.*}}, ptr {{%.*}}, i64 {{%.*}}, i64 {{%.*}})
; CHECK: [[U:%.*]] = call i32 @llvm.amdgcn.readfirstlane.i32(i32 [[A]])
; CHECK: call ptr @ompx__box_peer({{.*}}, i32 1, i32 [[U]], ptr
; CHECK: call i64 @ompx__box_piece(i64 {{.*}}, i32 64, i32 [[U]])
; CHECK-NOT: call void @ompx_pipelined_put
; The kernel with a put after it as well reads that post first, then its
; in-loop put's as the second.
; CHECK-LABEL: define {{.*}} @__omp_offloading_{{.*}}both
; CHECK: call void @ompx__after_put(i64 [[HB:-?[0-9]+]], i32 0,
; CHECK: call i32 @ompx__loop_after(i64 [[HB]], i32 1,
; CHECK-NOT: call void @ompx_pipelined_put
;
; Every kernel's record: peer, dst and length from the formals; the source
; is formal 3 (the launch's argument 2) plus 4 * (nx - 4) * ny. A record no
; kernel of this compile made is left alone.
; JSON-DAG: {"kernel":"__omp_offloading_{{[^"]*}}face{{[^"]*}}","puts":[{"bytes":{"op":"mul","ops":[{"op":"const","ty":"i64","v":16},{"n":{{[0-9]+}},"op":"arg","ty":"i64"}],"ty":"i64"},"dst":{"n":{{[0-9]+}},"op":"arg","ty":"ptr"},"index":0,"peer":{"op":"trunc","ops":[{"n":{{[0-9]+}},"op":"arg","ty":"i64"}],"ty":"i32"},"rel":{"op":"mul","ops":[{"op":"const","ty":"i64","v":4},{"op":"add","ops":[{"op":"const","ty":"i64","v":-4},{"n":{{[0-9]+}},"op":"arg","ty":"i64"}],"ty":"i64"},{"n":{{[0-9]+}},"op":"arg","ty":"i64"}],"ty":"i64"},"src_arg":2}]}
; JSON-DAG: {"kernel":"__omp_offloading_{{[^"]*}}mapped
; JSON-DAG: {"kernel":"__omp_offloading_{{[^"]*}}later
; JSON-DAG: {"kernel":"__omp_offloading_{{[^"]*}}both{{[^"]*}}","puts":[{{.*}}"index":1,
; JSON-DAG: stale
;
HEAD
    sed 's/^/; /; s/ *$//' Inputs/loop.cpp
    echo
    src_ir Inputs/loop.cpp --offload-device-only -O3 -Xclang -disable-llvm-passes
} > loop_device.ll

{
    cat <<'HEAD'
; Generated by gen.sh from Inputs/loop.cpp (host side) -- do not edit.
;
; The device test's compile records the in-loop puts; the host posts each
; one before the launch and ends it after, where it can.
; RUN: rm -rf %t.meta && mkdir -p %t.meta
; RUN: env GICC_MODE=put-discover GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -disable-output %s 2>/dev/null
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes='default<O3>' -disable-output %S/loop_device.ll 2>/dev/null
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -disable-output %s 2>&1 | %FileCheck %s --check-prefix=MSG
; RUN: env GICC_MODE=chunk-lower GICC_META_DIR=%t.meta %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-after-put -S %s 2>/dev/null | %FileCheck %s
;
; MSG-DAG: [gicc-after] __omp_offloading_{{.*}}face{{.*}}: 1 in-loop put(s) posted before the launch
; MSG-DAG: [gicc-after] __omp_offloading_{{.*}}mapped{{.*}}: an in-loop put is not posted {{.*}}: put 0: an argument it is computed from is not handed to the kernel as is (a mapped pointer?)
; MSG-DAG: [gicc-after] __omp_offloading_{{.*}}later{{.*}}: an in-loop put is not posted {{.*}}: the launch may not wait for the kernel (nowait)
; MSG-DAG: [gicc-after] __omp_offloading_{{.*}}both{{.*}}: 1 put(s) after the launch can go from the kernel
; MSG-DAG: [gicc-after] __omp_offloading_{{.*}}both{{.*}}: 1 in-loop put(s) posted before the launch
;
; Peer, dst, source and length computed from what the launch hands the
; kernel, armed when the peer is not negative.
; CHECK-LABEL: define {{.*}}@_Z4face
; CHECK: [[PEER:%.*]] = trunc i64 {{%.*}} to i32
; CHECK: [[REL:%.*]] = mul i64 {{%.*}}, {{%.*}}
; CHECK: [[LEN:%.*]] = mul i64 16, {{%.*}}
; CHECK: [[ARMED:%.*]] = icmp sge i32 [[PEER]], 0
; CHECK: [[ON:%.*]] = zext i1 [[ARMED]] to i32
; CHECK: [[SRC:%.*]] = getelementptr i8, ptr %0, i64 [[REL]]
; CHECK: call void @ompx__after_post(i64 [[H:-?[0-9]+]], i32 0, i32 2, i32 [[ON]], i32 [[PEER]], ptr %1, ptr [[SRC]], i64 [[REL]], i64 [[LEN]])
; CHECK-NEXT: call i32 @__tgt_target_kernel(
; CHECK-NEXT: call void @ompx__loop_done(i64 [[H]], i32 0)
; CHECK-LABEL: define {{.*}}@_Z6mapped
; CHECK-NOT: ompx__after_post
; CHECK-NOT: ompx__loop_done
; CHECK-LABEL: define {{.*}}@_Z5later
; CHECK-NOT: ompx__after_post
; CHECK-NOT: ompx__loop_done
; The put after the launch is post 0, the in-loop put post 1; each is
; ended after the launch in its own way.
; CHECK-LABEL: define {{.*}}@_Z4both
; CHECK: call void @ompx__after_post(i64 [[HB:-?[0-9]+]], i32 0,
; CHECK: call void @ompx__after_post(i64 [[HB]], i32 1,
; CHECK-NEXT: call i32 @__tgt_target_kernel(
; CHECK-NEXT: call void @ompx__loop_done(i64 [[HB]], i32 1)
; CHECK: call void @ompx__after_done(i64 [[HB]], i32 0,
; CHECK: declare
;
HEAD
    sed 's/^/; /; s/ *$//' Inputs/loop.cpp
    echo
    src_ir Inputs/loop.cpp --offload-host-only -O2
} > loop_host.ll
