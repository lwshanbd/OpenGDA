#!/usr/bin/env bash
# Regenerate the dist-chunk lit tests from Inputs/*.cpp.
#
# Each Inputs/<case>.cpp is compiled to NVPTX OpenMP device IR; <case>.ll is
# the RUN lines, the source as comments (its CHECK and IR lines included),
# and the IR. The pass reports on stderr (CHECK) and rewrites the IR (IR);
# without GICC_DIST_CHUNK it leaves every kernel alone (OFF).
#
# Usage: LLVM=<llvm prefix with NVPTX offload> ./gen.sh
set -euo pipefail
cd "$(dirname "$0")"
LLVM=${LLVM:-/shared/data1/Users/l1065028/llvm-22.1.7}

# LLVM 21 spells nocapture as captures(none); LLVM 19 (ROCm 6.4, Tioga)
# only parses the old form, which LLVM 21 still reads and upgrades.
portable() {
    grep -v '^; ModuleID' | sed 's/captures(none)/nocapture/g'
}

RUN='; RUN: env GICC_DIST_CHUNK=4096 %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-dist-chunk -disable-output %s 2>&1 | %FileCheck --allow-empty %s
; RUN: env GICC_DIST_CHUNK=4096 %opt -load-pass-plugin=%gicc_passes_so \
; RUN:   -passes=gicc-dist-chunk -S %s 2>/dev/null | %FileCheck --check-prefix=IR %s
; RUN: %opt -load-pass-plugin=%gicc_passes_so -passes=gicc-dist-chunk -S %s 2>&1 \
; RUN:   | %FileCheck --check-prefix=OFF %s
; OFF-NOT: gicc.dist.chunk
; OFF-NOT: [gicc-dist-chunk]'

for src in Inputs/*.cpp; do
    name=$(basename "$src" .cpp)
    ir=$("$LLVM/bin/clang++" -fopenmp -fopenmp-targets=nvptx64-nvidia-cuda \
        --offload-arch=sm_90 --offload-device-only -S -emit-llvm -O2 \
        "$src" -o - | portable)
    {
        echo "; Generated by gen.sh from $src -- do not edit."
        echo ";"
        echo "$RUN"
        echo ";"
        sed 's/^/; /; s/ *$//' "$src"
        echo
        echo "$ir"
    } > "$name.ll"
done
